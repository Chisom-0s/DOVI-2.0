const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const remoteDumpPath = path.join(rootDir, 'scripts/remote_products_dump.json');
const backendCatalogPath = path.join(rootDir, 'backend/products_catalog.json');
const backendDeliveryStorePath = path.join(rootDir, 'backend/delivery_store.json');
const adminDeliveryStorePath = path.join(rootDir, 'admin/public/delivery_store.json');
const frontendDeliveryStorePath = path.join(rootDir, 'frontend/public/delivery_store.json');
const frontendSeedPath = path.join(rootDir, 'frontend/src/api/seedProducts.ts');

const remoteProducts = JSON.parse(fs.readFileSync(remoteDumpPath, 'utf8'));
const existingCatalog = JSON.parse(fs.readFileSync(backendCatalogPath, 'utf8'));
const existingDeliveryStore = JSON.parse(fs.readFileSync(backendDeliveryStorePath, 'utf8'));

console.log(`Loaded remote products: ${remoteProducts.length}`);
console.log(`Loaded existing catalog products: ${existingCatalog.length}`);
console.log(`Loaded existing delivery store products: ${existingDeliveryStore.products.length}`);

// Build 54 product list for products_catalog.json
// Preserve existing catalog entries (which may have local overrides or comments), and append any missing remote products
const catalogMap = new Map(existingCatalog.map(p => [p.id, p]));
remoteProducts.forEach(p => {
  if (!catalogMap.has(p.id)) {
    catalogMap.set(p.id, p);
  }
});
const fullCatalog = Array.from(catalogMap.values());
console.log(`Full catalog count: ${fullCatalog.length}`);
fs.writeFileSync(backendCatalogPath, JSON.stringify(fullCatalog, null, 2), 'utf8');
console.log(`Updated ${backendCatalogPath}`);

// Build 54 product list for delivery_store.json
const deliveryProductMap = new Map(existingDeliveryStore.products.map(p => [p.id, p]));
remoteProducts.forEach(p => {
  if (!deliveryProductMap.has(p.id)) {
    deliveryProductMap.set(p.id, p);
  }
});
existingDeliveryStore.products = Array.from(deliveryProductMap.values());
console.log(`Full delivery store products count: ${existingDeliveryStore.products.length}`);
fs.writeFileSync(backendDeliveryStorePath, JSON.stringify(existingDeliveryStore, null, 2), 'utf8');
console.log(`Updated ${backendDeliveryStorePath}`);

// Sync to admin and frontend public delivery_store.json
fs.writeFileSync(adminDeliveryStorePath, JSON.stringify(existingDeliveryStore, null, 2), 'utf8');
console.log(`Updated ${adminDeliveryStorePath}`);

fs.writeFileSync(frontendDeliveryStorePath, JSON.stringify(existingDeliveryStore, null, 2), 'utf8');
console.log(`Updated ${frontendDeliveryStorePath}`);

// Update frontend/src/api/seedProducts.ts
const seedContent = `// Autogenerated seed catalog containing all ${fullCatalog.length} live published products
export const SEED_RAW_PRODUCTS: any[] = ${JSON.stringify(fullCatalog, null, 2)};
`;
fs.writeFileSync(frontendSeedPath, seedContent, 'utf8');
console.log(`Updated ${frontendSeedPath}`);

console.log('All product stores successfully synchronized to 54 products!');
